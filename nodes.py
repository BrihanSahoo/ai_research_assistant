# Task Specialization
def analyzer_node(state:ResearchState):
    question = state['question']
    
    prompt = f"""
    You are an expert AI research assistant.

    Analyze the user's research question.

    Identify:

    1. Main topic
    2. User's actual objective
    3. Important subtopics
    4. Type of answer required
    5. Whether external research is required

    User Question:
    {question}

    Provide a concise structured analysis.
    """
    
    result = llm.invoke(prompt)
    
    return {
        "analysis" : result.content
    }
    
    



def planer_node(state:ResearchState):
    
    question = state['question']
    analysis = state['analysis']
    
    prompt = f"""
    You are an expert research planner.

    Original Question:
    {question}

    Query Analysis:
    {analysis}

    Break this research task into 3 to 5
    specific and independent search queries.

    Requirements:
    1. Cover all important aspects.
    2. Avoid duplicate queries.
    3. Each query should be useful for research.
    4. Keep queries specific.

    Return one query per line.
    Do not include numbering or explanations.
    """
    response = llm.invoke(prompt)
    queries = [
        line.split("- ").strip()
        for line in response.content.splitlines()
        if line.strip()
    ]
    
    return {
        "research_plan" : queries
    }
    
 
 
 # Search the web   
def researcher_node(state:ResearchState):
    
    queries = state['research_plan']
    all_results = []
    for query in queries:
        results = search_tool(query)
        
        for result in results:
            all_results.append({
                "title": result["title"],
                "content": result["content"],
                "url": result["url"]
            })
    
    return {
        'research_results' : all_results
    }
    


# Generate answer based on the search results and question
def answer_generator(state:ResearchState):
    
    question = state['question']
    research = state['research_results']
    feedback = state.get("feedback","")
    
    prompt = f"""
    You are an expert research assistant.

    User question:
    {question}

    Research information:
    {research}

    Previous evaluator feedback:
    {feedback}

    Instructions:
    - Answer the original question.
    - Use the research information.
    - Explain concepts clearly.
    - Include examples.
    - Do not invent facts.
    - Include source URLs where relevant.
    """
    
    response = llm.invoke(prompt)
    
    return {
        "answer" : response.content
    }
    
    
    

# Answer evaluation
def evaluator_node(state:ResearchState):
    question = state['question']
    answer = state['answer']
    
    prompt = f"""
    You are a strict AI answer evaluator.

    Your job is to evaluate the quality of an answer
    generated by an AI research assistant.

    Original User Question:
    {question}

    Generated Answer:
    {answer}

    Evaluate the answer using these criteria:

    1. Accuracy:
       Are the claims factually correct?
       Identify potentially incorrect claims.

    2. Completeness:
       Does the answer cover all important parts
       of the user's question?

    3. Relevance:
       Does the answer directly address the question?

    4. Clarity:
       Is the explanation understandable and organized?

    5. Evidence:
       Are factual claims supported by the research?

    Approval rules:

    - Approve only if the answer is sufficiently
      complete, relevant and supported.
    - Reject if important information is missing.
    - Reject if important claims appear unsupported.
    - Give specific feedback explaining what to improve.
    - Do not reject merely because you prefer
      a different writing style.

    Return ONLY valid JSON in this exact format:

    {{
        "approved": true,
        "feedback": "Your evaluation feedback"
    }}
    """
    
    response = llm.invoke(prompt)
    
    try:
        evaluation = json.load(response.content)
        approved = evaluation['approved']
        feedback = evaluation['feedback']
        
        if not isinstance(approved,bool):
            raise ValueError("approved must be boolean")
        if not isinstance(feedback,str):
            raise ValueError("feedback should be string")
    except (ValueError,KeyError,TypeError):
        approved = False
        feedback = (
            "Evaluator returned an invalid response. "
            "Please generate and evaluate again."
        )
        
        return {
            "approved": approved,
            "feedback": feedback,
            "iteration": state.get("iteration", 0) + 1
        }